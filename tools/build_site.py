def crumbs(items):
    """items = [(label, href_or_None), ...] — last one has no href."""
    lis = []
    for label, href in items:
        if href:
            lis.append(f'<li><a href="{href}">{label}</a></li>')
        else:
            lis.append(f'<li aria-current="page">{label}</li>')
    return ('<nav class="container crumbs" aria-label="Breadcrumb"><ol>'
            + "".join(lis) + "</ol></nav>")


def crumb_ld(items, depth):
    """JSON-LD BreadcrumbList. items same shape as crumbs()."""
    els = []
    for i, (label, href) in enumerate(items, start=1):
        # hrefs carry the {P} depth placeholder — strip it, these must be absolute
        clean = (href or "").replace("{P}", "")
        url = B["domain"] + "/" + clean
        item = f', "item": "{url}"' if href else ""
        els.append('{"@type": "ListItem", "position": %d, "name": "%s"%s}' % (i, label, item))
    return ('<script type="application/ld+json">{"@context":"https://schema.org",'
            '"@type":"BreadcrumbList","itemListElement":[' + ",".join(els) + "]}</script>")


